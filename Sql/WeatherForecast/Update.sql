-- 一覧で編集した行の更新。パラメータは 0 始まりの番号を波かっこで囲んで指定する
-- 注意: SQL 文全体が string.Format で処理されるため、コメント内でも波かっこを書かないこと (書く場合は二重にする)
-- 他の人の変更を上書きしないよう、画面に読み込んだ時点の最終更新日 (4 番) と今の最終更新日が同じ行だけを更新し、
-- 最終更新日を今の日時にする。更新件数が 0 件なら、読み込んだ後に他の人が変更または削除している。
-- now() はトランザクションの開始時刻なので、まとめて保存した行は同じ最終更新日になる
UPDATE weather_forecasts
SET date = {0},
    temperature_c = {1},
    summary = {2},
    updated_at = now()
WHERE id = {3}
  AND updated_at = {4}
